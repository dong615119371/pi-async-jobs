/**
 * Durable job records.
 *
 * Why persist at all: a job can finish while the session that started it is gone
 * (Pi closed, crashed, or reloaded). Without a record on disk the result is lost
 * and the work has to be redone. With one, the next session can report it.
 *
 * Kept deliberately small. The reference project spends ~550 lines here on
 * canonical serialisation, hash framing, and crash-consistent directories; that
 * exists to make results verifiable across processes, which we do not need. What we
 * do need is: a file per job, written atomically, and a safe read-back that ignores
 * anything half-written.
 *
 * Atomic write sequence: write `<id>.json.tmp`, then rename over `<id>.json`. Rename
 * is the atomic step, so a reader never observes a partial document.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import type { JobRecord } from "./types.ts";

export class JobStore {
	private readonly root: string;
	private ready = false;

	constructor(root: string) {
		this.root = root;
	}

	/** Create the directory. Safe to call more than once. */
	init(): void {
		if (this.ready) return;
		fs.mkdirSync(this.root, { recursive: true });
		this.ready = true;
	}

	dir(): string {
		return this.root;
	}

	private fileFor(id: string): string {
		// Ids are generated by us (`aj-<hex>`), but never let one escape the directory.
		const safe = id.replace(/[^\w.-]+/g, "_");
		return path.join(this.root, `${safe}.json`);
	}

	outputPathFor(id: string): string {
		const safe = id.replace(/[^\w.-]+/g, "_");
		return path.join(this.root, `${safe}.output`);
	}

	/** Persist a record. Never throws: losing a record must not fail the job. */
	write(record: JobRecord): void {
		try {
			this.init();
			const target = this.fileFor(record.id);
			const tmp = `${target}.tmp`;
			fs.writeFileSync(tmp, JSON.stringify(record), { encoding: "utf8", mode: 0o600 });
			fs.renameSync(tmp, target);
		} catch {
			/* best effort */
		}
	}

	read(id: string): JobRecord | null {
		try {
			const raw = fs.readFileSync(this.fileFor(id), "utf8");
			const parsed = JSON.parse(raw);
			if (parsed && typeof parsed.id === "string") return parsed as JobRecord;
			return null;
		} catch {
			// Missing, unreadable, or half-written: treat as absent rather than throw.
			return null;
		}
	}

	/** Every readable record in the store, newest first. Unparseable files are skipped. */
	listAll(): JobRecord[] {
		let entries: string[];
		try {
			entries = fs.readdirSync(this.root);
		} catch {
			return [];
		}
		const records: JobRecord[] = [];
		for (const entry of entries) {
			if (!entry.endsWith(".json")) continue; // skips .tmp and .output
			const record = this.read(entry.slice(0, -".json".length));
			if (record) records.push(record);
		}
		records.sort((a, b) => b.startedAt - a.startedAt);
		return records;
	}

	remove(id: string): void {
		try {
			fs.rmSync(this.fileFor(id), { force: true });
		} catch {
			/* best effort */
		}
		try {
			fs.rmSync(this.outputPathFor(id), { force: true });
		} catch {
			/* best effort */
		}
	}

	/**
	 * Drop records older than `maxAgeMs` and keep at most `maxCount` newest ones.
	 * Running jobs are never pruned: their record is the only place the id lives.
	 */
	prune(maxCount: number, maxAgeMs: number): number {
		const cutoff = Date.now() - maxAgeMs;
		const all = this.listAll();
		let removed = 0;
		let kept = 0;
		for (const record of all) {
			const finished = record.state !== "running";
			const tooOld = finished && record.finishedAt !== undefined && record.finishedAt < cutoff;
			const overCount = finished && kept >= maxCount;
			if (tooOld || overCount) {
				this.remove(record.id);
				removed++;
			} else if (finished) {
				kept++;
			}
		}
		return removed;
	}

	/** Latest bytes of a job's output file, capped at `maxBytes` from the end. */
	tailOutput(id: string, maxBytes: number): { text: string; truncated: boolean; totalBytes: number } {
		try {
			const file = this.outputPathFor(id);
			const size = fs.statSync(file).size;
			const start = Math.max(0, size - maxBytes);
			const length = size - start;
			const fd = fs.openSync(file, "r");
			try {
				const buffer = Buffer.alloc(length);
				fs.readSync(fd, buffer, 0, length, start);
				return { text: buffer.toString("utf8"), truncated: start > 0, totalBytes: size };
			} finally {
				fs.closeSync(fd);
			}
		} catch {
			return { text: "", truncated: false, totalBytes: 0 };
		}
	}
}
